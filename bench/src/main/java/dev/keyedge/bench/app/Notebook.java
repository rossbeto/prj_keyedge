package dev.keyedge.bench.app;

import dev.keyedge.bench.domain.BenchResult;
import dev.keyedge.bench.domain.StepResult;
import dev.keyedge.bench.domain.Steps;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * The generated parts of docs/lab-notebook.md and README.md. The prose of each experiment stays
 * hand-written; what must follow the data is generated between {@code <!-- name:begin -->} and
 * {@code <!-- name:end -->} markers: the index of verdicts and the bench sections. {@link
 * #verdictMismatches} checks that every hand-written "verdict **x**" agrees with its results file.
 */
public final class Notebook {
  private static final Pattern SECTION =
      Pattern.compile("(?m)^## ([a-z0-9-]+) \\(Phase (\\d{3})\\)");

  /** The first bold word after "**Result**": "**Result** (link): [verdict] **confirmed** ...". */
  private static final Pattern VERDICT = Pattern.compile("\\*\\*Result\\*\\*[^*]*\\*\\*([a-z]+)");

  private Notebook() {}

  /**
   * One experiment's verdicts as recorded.
   *
   * @param verdicts verdict per results file (several for per-target experiments)
   */
  public record LabEntry(String id, Map<String, String> verdicts) {
    public LabEntry {
      verdicts =
          java.util.Collections.unmodifiableSortedMap(new TreeMap<>(verdicts)); // ordered: rendered
    }

    /** One word if all files agree, else "file: verdict" pairs. */
    public String verdict() {
      var distinct = verdicts.values().stream().distinct().toList();
      if (distinct.size() == 1) {
        return distinct.getFirst();
      }
      List<String> parts = new ArrayList<>();
      new TreeMap<>(verdicts).forEach((f, v) -> parts.add(v + " (" + f + ")"));
      return String.join(", ", parts);
    }
  }

  /** Phase per experiment id, from the "## id (Phase NNN)" headings already in the notebook. */
  public static Map<String, String> phases(String doc) {
    Map<String, String> out = new LinkedHashMap<>();
    Matcher m = SECTION.matcher(doc);
    while (m.find()) {
      out.putIfAbsent(m.group(1), m.group(2));
    }
    return out;
  }

  /** The index table: experiment, phase, verdict, results files; notebook order, then the rest. */
  public static String index(List<LabEntry> entries, Map<String, String> phases) {
    Map<String, LabEntry> byId = new LinkedHashMap<>();
    entries.forEach(e -> byId.put(e.id(), e));
    List<String> order = new ArrayList<>(phases.keySet());
    byId.keySet().stream().filter(id -> !order.contains(id)).sorted().forEach(order::add);
    StringBuilder b = new StringBuilder();
    b.append("| Experiment | Phase | Verdict | Results |\n|---|---|---|---|\n");
    for (String id : order) {
      LabEntry e = byId.get(id);
      String files =
          e == null
              ? "see section"
              : String.join(
                  ", ",
                  e.verdicts().keySet().stream()
                      .map(f -> "[" + f.substring(f.lastIndexOf('/') + 1) + "](../" + f + ")")
                      .toList());
      b.append("| [")
          .append(id)
          .append("](#")
          .append(id)
          .append("-phase-")
          .append(phases.getOrDefault(id, "015"))
          .append(") | ")
          .append(phases.getOrDefault(id, "015"))
          .append(" | ")
          .append(e == null ? "see section" : "**" + e.verdict() + "**")
          .append(" | ")
          .append(files)
          .append(" |\n");
    }
    long confirmed = byId.values().stream().filter(e -> e.verdict().equals("confirmed")).count();
    long refuted = byId.values().stream().filter(e -> e.verdict().equals("refuted")).count();
    long inconclusive =
        byId.values().stream().filter(e -> e.verdict().equals("inconclusive")).count();
    b.append("\n")
        .append(order.size())
        .append(" experiments: ")
        .append(confirmed)
        .append(" confirmed, ")
        .append(refuted)
        .append(" refuted, ")
        .append(inconclusive)
        .append(" inconclusive")
        .append(byId.size() < order.size() ? ", the rest described in their sections" : "")
        .append(" (generated by `make report` from the results files).\n");
    return b.toString();
  }

  /** A bench experiment's section, from its results file only. */
  public static String benchSection(BenchResult r, String phase, String resultPath, String chart) {
    StringBuilder b = new StringBuilder();
    b.append("## ").append(r.scenario()).append(" (Phase ").append(phase).append(")\n\n");
    b.append("**Hypothesis.** ").append(r.hypothesis()).append("\n\n");
    b.append("**Prediction** (written ")
        .append(r.prediction().writtenAt())
        .append(", before the load). ")
        .append(r.prediction().statement())
        .append("\n\n");
    List<Integer> rates =
        r.steps().stream().map(StepResult::offeredRps).distinct().sorted().toList();
    List<String> variants = r.steps().stream().map(StepResult::variant).distinct().toList();
    b.append("**Method.** k6 constant-arrival-rate in a container; ")
        .append(rates.size())
        .append(" offered rates × ")
        .append(variants.size())
        .append(" variants × ")
        .append(r.steps().stream().mapToInt(StepResult::repetition).max().orElse(1))
        .append(" repetitions (medians below; generator-bound steps excluded); SLO p99 ≤ ")
        .append(SvgChart.fmt(r.slo().p99Ms()))
        .append(" ms and errors ≤ ")
        .append(SvgChart.fmt(r.slo().maxErrorRatio() * 100))
        .append(" %. `make bench S=")
        .append(r.scenario())
        .append("`.\n\n");
    b.append(stepTable(r, variants, rates));
    b.append("\nSaturation (highest rate meeting the SLO): ");
    List<String> sat = new ArrayList<>();
    r.saturationRps().entrySet().stream()
        .sorted(Map.Entry.comparingByKey())
        .forEach(
            e -> sat.add(e.getKey() + " " + (e.getValue() == 0 ? "none" : e.getValue() + " rps")));
    b.append(String.join(", ", sat)).append(".\n\n");
    if (!chart.isEmpty()) {
      b.append("![").append(r.scenario()).append("](").append(chart).append(")\n\n");
    }
    b.append("**Result** ([")
        .append(resultPath)
        .append("](../")
        .append(resultPath)
        .append(")): verdict **")
        .append(r.verdict())
        .append("**. ")
        .append(r.verdictDetail())
        .append(".\n\n");
    b.append(where(r));
    return b.toString();
  }

  private static String stepTable(BenchResult r, List<String> variants, List<Integer> rates) {
    StringBuilder b = new StringBuilder();
    b.append(
        "| Variant | Rate (rps) | p50 ms | p99 ms | Errors % | Shed % | CPU ms/req | Valid steps |\n|---|---|---|---|---|---|---|---|\n");
    for (String v : variants) {
      for (int rate : rates) {
        long valid =
            r.steps().stream()
                .filter(s -> s.variant().equals(v) && s.offeredRps() == rate && s.valid())
                .count();
        long all =
            r.steps().stream().filter(s -> s.variant().equals(v) && s.offeredRps() == rate).count();
        if (all == 0) {
          continue;
        }
        b.append("| ")
            .append(v)
            .append(" | ")
            .append(rate)
            .append(" | ")
            .append(cell(Steps.median(r.steps(), v, rate, StepResult::p50Ms).orElse(Double.NaN)))
            .append(" | ")
            .append(cell(Steps.median(r.steps(), v, rate, StepResult::p99Ms).orElse(Double.NaN)))
            .append(" | ")
            .append(
                cell(
                    Steps.median(r.steps(), v, rate, s -> s.errorRatio() * 100).orElse(Double.NaN)))
            .append(" | ")
            .append(
                cell(
                    Steps.median(
                            r.steps(),
                            v,
                            rate,
                            s -> s.requests() == 0 ? 0 : 100.0 * s.shed() / s.requests())
                        .orElse(Double.NaN)))
            .append(" | ")
            .append(
                cell(
                    Steps.median(
                            r.steps(),
                            v,
                            rate,
                            s -> s.cpuPerReqMs() == null ? Double.NaN : s.cpuPerReqMs())
                        .orElse(Double.NaN)))
            .append(" | ")
            .append(valid)
            .append("/")
            .append(all)
            .append(" |\n");
      }
    }
    return b.toString();
  }

  private static String where(BenchResult r) {
    StringBuilder b = new StringBuilder();
    var fp = r.fingerprint();
    b.append(
        String.format(
            Locale.ROOT,
            "**Where.** %d CPUs, %d MiB, load average %.1f at the start, Docker %s, emulator %s %s, commit %s%s.%s\n",
            fp.cpus(),
            fp.memTotalMb(),
            fp.loadAverage1m(),
            fp.docker(),
            fp.emulatorKind(),
            fp.emulatorVersion(),
            r.git().sha(),
            r.git().dirty() ? " (dirty)" : "",
            r.notes().isEmpty() ? "" : " Notes: " + String.join("; ", r.notes()) + "."));
    return b.toString();
  }

  private static String cell(double v) {
    return Double.isNaN(v) ? "—" : String.format(Locale.ROOT, "%.2f", v);
  }

  /** Replaces the content between the markers; the markers must exist. */
  public static String replaceBlock(String doc, String name, String content) {
    String begin = "<!-- " + name + ":begin -->";
    String end = "<!-- " + name + ":end -->";
    int a = doc.indexOf(begin);
    int z = doc.indexOf(end);
    if (a < 0 || z < a) {
      throw new IllegalArgumentException("markers " + begin + " / " + end + " missing");
    }
    return doc.substring(0, a + begin.length()) + "\n" + content.strip() + "\n" + doc.substring(z);
  }

  /** "id: notebook says x, results say y" for every section whose stated verdict disagrees. */
  public static List<String> verdictMismatches(String doc, Map<String, String> verdictById) {
    List<String> out = new ArrayList<>();
    Matcher m = SECTION.matcher(doc);
    List<int[]> bounds = new ArrayList<>();
    List<String> ids = new ArrayList<>();
    while (m.find()) {
      bounds.add(new int[] {m.start()});
      ids.add(m.group(1));
    }
    for (int i = 0; i < ids.size(); i++) {
      int from = bounds.get(i)[0];
      int to = i + 1 < ids.size() ? bounds.get(i + 1)[0] : doc.length();
      String expected = verdictById.get(ids.get(i));
      if (expected == null) {
        continue;
      }
      Matcher v = VERDICT.matcher(doc.substring(from, to));
      String stated = v.find() ? v.group(1) : "(none)";
      if (!expected.startsWith(stated)) {
        out.add(ids.get(i) + ": notebook says " + stated + ", results say " + expected);
      }
    }
    return out;
  }
}
